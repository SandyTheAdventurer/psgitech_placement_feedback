const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const PDFDocument = require('pdfkit');
const cfg = require('../server/config');
const db = require('../server/db');

if (db.prepare('SELECT COUNT(*) n FROM companies').get().n) {
  console.log('Database already has companies — demo seed skipped.');
  process.exit(0);
}

function samplePdf(file, company, year, sections) {
  return new Promise((resolve) => {
    const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Title: `${company} ${year} guide (sample)` } });
    const out = fs.createWriteStream(file);
    doc.pipe(out);
    doc.rect(0, 0, doc.page.width, 150).fill('#0f2747');
    doc.fillColor('#f5c04a').font('Helvetica-Bold').fontSize(10).text('PLACEMENT PREPARATION  -  SAMPLE DOCUMENT', 56, 52);
    doc.fillColor('#ffffff').fontSize(26).text(`${company} - Interview Guide ${year}`, 56, 74);
    doc.fillColor('#b8c7de').font('Helvetica').fontSize(11).text('Demo content generated by the seed script. Replace it from the admin dashboard.', 56, 116);
    doc.fillColor('#1d2b3f').moveDown(4);
    doc.y = 190;
    sections.forEach((s, i) => {
      doc.font('Helvetica-Bold').fontSize(15).fillColor('#0f2747').text(`${i + 1}. ${s.title}`);
      doc.moveDown(0.4);
      doc.font('Helvetica').fontSize(11).fillColor('#33415a');
      s.items.forEach((q) => doc.text(`•  ${q}`, { indent: 8, paragraphGap: 4 }));
      doc.moveDown(1);
    });
    doc.end();
    out.on('finish', resolve);
  });
}

